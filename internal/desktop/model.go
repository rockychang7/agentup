func digest(value any) string {
	data, _ := json.Marshal(value)
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])[:24]
}

func installationID(info Installation) string {
	path := info.Path
	if info.Source == "msix" {
		// Windows embeds the changing package version in InstallLocation.
		path = ""
	}
	if strings.Contains(path, `:\`) {
		path = strings.ToLower(path)
	}
	return info.ProductID + ":" + digest([]string{path, info.PackageID, info.Scope, info.Arch})
}

var numericVersion = regexp.MustCompile(`^\d+(?:\.\d+){1,3}$`)

// compareVersion accepts numeric desktop versions, including four-part MSIX versions.
// Package revisions and prereleases need a channel-specific comparator, not guessing.
func compareVersion(a, b string) (int, bool) {
	if !numericVersion.MatchString(a) || !numericVersion.MatchString(b) {
		return 0, false
	}
	left, right := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < max(len(left), len(right)); i++ {
		var x, y uint64
		var err error
		if i < len(left) {
			x, err = strconv.ParseUint(left[i], 10, 64)
			if err != nil {
				return 0, false
			}
		}
		if i < len(right) {
			y, err = strconv.ParseUint(right[i], 10, 64)
			if err != nil {
				return 0, false
			}
		}
		if x < y {
			return -1, true
		}
		if x > y {
			return 1, true
		}
	}
	return 0, true
}

func supportedLine(product, before, after string) bool {
	if product == "antigravity.desktop" {
		major, err := strconv.Atoi(strings.Split(before, ".")[0])
		if err != nil || major < 2 {
			return false
		}
	}
	if product == "opencode.desktop" || product == "antigravity.desktop" {
		return strings.Split(before, ".")[0] == strings.Split(after, ".")[0]
	}
	return true
}

func missing(p Product) Installation {
	return Installation{
		ID: "missing:" + p.ID, ProductID: p.ID, Name: p.Name, Kind: "desktop",
		LatestCheck: model.CheckOffline, Source: "unknown", Channel: "unknown",
		Running: "unknown", Capability: Blocked, Reason: "not_installed", UpdateURL: p.URL,
	}
}

func rawInstallation(p Product) Installation {
	info := missing(p)
	info.ID = ""
	info.Installed = true
	info.Capability, info.Reason = Guided, "manual_channel"
	return info
}

func candidate(info *Installation, version string) {
	info.LatestVersion, info.LatestCheck = version, model.CheckOK
	cmp, ok := compareVersion(info.Version, version)
	if !ok {
		info.LatestCheck, info.Reason = model.CheckUnavailable, "version_uncomparable"
		return
	}
	if cmp < 0 && !supportedLine(info.ProductID, info.Version, version) {
		info.Capability, info.Reason = Guided, "release_line_change"
		info.LatestCheck = model.CheckUnavailable
		return
	}
	info.UpgradeAvailable = cmp < 0
}

// planSpec is how a platform scanner says an installation could be updated.
// Scan applies process checks and channel acceptance before turning it into a Plan.
type planSpec struct {
	command []string
	asset   *Asset
	// unknownOK lets the channel itself decide whether an update applies,
	// for sources such as msstore that do not report an available version.
	unknownOK  bool
	standalone bool
}

func executable(capability Capability) bool {
	return capability == Automatic || capability == Interactive || capability == Privileged
}

func makePlan(info Installation, spec planSpec) *Plan {
	if !info.Installed || info.Capability == Blocked {
		return nil
	}
	plan := &Plan{
		Installation: info.ID, ProductID: info.ProductID, BeforeVersion: info.Version,
		TargetVersion: info.LatestVersion, Path: info.Path, PackageID: info.PackageID,
		Source: info.Source, Scope: info.Scope, Arch: info.Arch, Channel: info.Channel,
		Action: ActionGuide, URL: info.UpdateURL,
	}
	if executable(info.Capability) {
		if !info.UpgradeAvailable && !(spec.unknownOK && info.LatestCheck != model.CheckOK) {
			return nil
		}
		switch info.Capability {
		case Automatic:
			plan.Action, plan.Command = ActionCommand, spec.command
		case Privileged:
			plan.Action, plan.Command, plan.RequiresAdmin = ActionPrivileged, spec.command, true
		case Interactive:
			plan.Action, plan.Asset = ActionInstaller, spec.asset
		}
		if len(plan.Command) == 0 && plan.Asset == nil {
			return nil
		}
		plan.URL, plan.RequiresExit, plan.Standalone = "", true, spec.standalone
	}
	plan.ID = digest(plan)
	return plan
}

func (s Snapshot) Find(id string) (Installation, error) {
	for _, info := range s.Installations {
		if info.ID == id {
			return info, nil
		}
	}
	return Installation{}, fmt.Errorf("desktop installation no longer exists: %s", id)
}
